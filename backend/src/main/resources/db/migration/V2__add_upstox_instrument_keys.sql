ALTER TABLE stock
    ADD COLUMN instrument_key VARCHAR(100) NULL;

UPDATE stock
SET instrument_key = CASE symbol
    WHEN 'RELIANCE' THEN 'NSE_EQ|INE002A01018'
    WHEN 'TCS' THEN 'NSE_EQ|INE467B01029'
    WHEN 'HDFCBANK' THEN 'NSE_EQ|INE040A01034'
    WHEN 'ICICIBANK' THEN 'NSE_EQ|INE090A01021'
    WHEN 'INFY' THEN 'NSE_EQ|INE009A01021'
    WHEN 'ITC' THEN 'NSE_EQ|INE154A01025'
    WHEN 'SBIN' THEN 'NSE_EQ|INE062A01020'
    WHEN 'BHARTIARTL' THEN 'NSE_EQ|INE397D01024'
    WHEN 'LT' THEN 'NSE_EQ|INE018A01030'
    WHEN 'MARUTI' THEN 'NSE_EQ|INE585B01010'
    WHEN 'WIPRO' THEN 'NSE_EQ|INE075A01022'
    WHEN 'AXISBANK' THEN 'NSE_EQ|INE238A01034'
    WHEN 'SUNPHARMA' THEN 'NSE_EQ|INE044A01036'
    WHEN 'TATASTEEL' THEN 'NSE_EQ|INE081A01020'
END
WHERE symbol IN (
    'RELIANCE', 'TCS', 'HDFCBANK', 'ICICIBANK', 'INFY', 'ITC', 'SBIN',
    'BHARTIARTL', 'LT', 'MARUTI', 'WIPRO', 'AXISBANK', 'SUNPHARMA', 'TATASTEEL'
);
